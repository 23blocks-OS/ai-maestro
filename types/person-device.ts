/**
 * A paired device: an app that says "I am person X" to a host it is connected to.
 *
 * Stored per host, separate from the person record. A person's record lives on one host (where the
 * operator added them) but their app can be connected to several, and each of those hosts needs to
 * know the app is theirs. A person is online when any host has a recently seen device for them.
 *
 * No authentication, by design: a device states who it is and nobody checks. This is a label in a
 * trusted network, not a login.
 */
export const PUSH_TYPES = ['needs_you', 'card_waiting', 'call'] as const
export type PushType = typeof PUSH_TYPES[number]

export interface PersonDevice {
  /** Generated by the app and kept across launches */
  deviceId: string
  /** The person's id, as listed by GET /api/people on whichever host holds the record */
  personId: string
  /** A snapshot of the name, so a host without the record can still show it */
  personName?: string
  deviceName?: string
  platform?: string
  appVersion?: string
  /** Expo push token of the phone. Never returned by the API: whoever holds it can notify the phone. */
  pushToken?: string
  /** What the person wants pushed to this device; empty means nothing */
  pushTypes?: PushType[]
  firstSeenAt: string
  lastSeenAt: string
}

/** A device as a host returns it */
export interface PersonDeviceRecord extends Omit<PersonDevice, 'pushToken'> {
  hostId: string
  /** A push token is stored for this device (the token itself is not returned) */
  pushEnabled: boolean
  /** Seen within the last 90 seconds (the app re-sends the pairing as a heartbeat) */
  online: boolean
}
