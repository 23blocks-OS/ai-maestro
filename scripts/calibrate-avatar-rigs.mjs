#!/usr/bin/env node
/**
 * One-time (re-runnable) calibration of avatar face anchors.
 *
 * WHY THIS EXISTS
 *
 * The animated call avatar warps a band of the portrait to open the mouth and
 * clips lids over the eyes, so it needs to know where those features are. The
 * first attempt used one anchor set per avatar folder, on the assumption that
 * a generated set would be consistently framed.
 *
 * It is not. Measured on the shipped renders, the `women` set alone spans an
 * eye line from 0.337 to 0.411 of image height — and at the wrong end of that
 * range the mouth shadow lands on the chin and the eyelids draw under the eyes.
 * It looks broken, and no amount of softening the warp hides it.
 *
 * So anchors are measured per avatar, once, offline, and committed.
 *
 * HOW
 *
 * Eyes are detected with OpenCV's Haar cascades, which are reliable on clean
 * frontal portraits. Everything else is derived from the INTER-OCULAR DISTANCE
 * rather than from the image or the face box, because IOD is the standard
 * anthropometric scale and it is invariant to how tightly the portrait is
 * cropped. Cross-checked against hand-measured mouths on four faces:
 *
 *     (mouthY - eyeY) / IOD  =  1.06, 0.99, 1.09, 1.03    → 1.04 ± 5%
 *
 * That consistency is the whole justification for the approach.
 *
 * ROBOTS
 *
 * Haar detects none of them, which is expected — many have visors, lenses or
 * no face at all. They fall back to a set default measured by hand, and their
 * jaw warp is damped (see FaceRig.jawScale) because a rigid faceplate that
 * stretches reads as a rendering bug rather than as speech.
 *
 * USAGE
 *
 *   python3 -m venv /tmp/cal && /tmp/cal/bin/pip install "opencv-python-headless<5"
 *   CAL_PYTHON=/tmp/cal/bin/python node scripts/calibrate-avatar-rigs.mjs
 *
 * Writes BOTH:
 *   lib/avatar-rigs.generated.ts   — bundled, for the web client
 *   public/avatars/face-anchors.json — served, for the mobile app and anything
 *                                      else that must stay in sync as avatars
 *                                      are added without shipping a new build
 *
 * Re-run when avatars are added.
 */

import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const AVATAR_DIR = path.join(ROOT, 'public', 'avatars')
const OUT = path.join(ROOT, 'lib', 'avatar-rigs.generated.ts')
const PYTHON = process.env.CAL_PYTHON || 'python3'

const DETECT = `
import cv2, json, sys, os
face = cv2.CascadeClassifier(cv2.data.haarcascades + 'haarcascade_frontalface_default.xml')
eyes = cv2.CascadeClassifier(cv2.data.haarcascades + 'haarcascade_eye.xml')
out = {}
for name in sorted(os.listdir(sys.argv[1])):
    if not name.lower().endswith('.png'):
        continue
    img = cv2.imread(os.path.join(sys.argv[1], name))
    if img is None:
        continue
    g = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    h, w = g.shape
    faces = face.detectMultiScale(g, 1.08, 5, minSize=(int(w * 0.15), int(h * 0.15)))
    if len(faces) == 0:
        continue
    x, y, fw, fh = max(faces, key=lambda b: b[2] * b[3])
    # Upper 60% of the face box only: the eye cascade fires on nostrils and
    # mouth corners otherwise, and a false "eye" wrecks the IOD.
    found = eyes.detectMultiScale(g[y:y + int(fh * 0.6), x:x + fw], 1.05, 6)
    if len(found) < 2:
        continue
    found = sorted(found, key=lambda e: e[0])
    left, right = found[0], found[-1]
    cx = [x + e[0] + e[2] / 2 for e in (left, right)]
    cy = [y + e[1] + e[3] / 2 for e in (left, right)]
    iod = abs(cx[1] - cx[0]) / w
    # Sanity gate. A human IOD is ~0.10-0.25 of a portrait's width; anything
    # outside that means the cascade matched two things that are not eyes, and
    # a bad anchor is worse than the set default.
    if not (0.08 < iod < 0.30):
        continue
    out[name] = [round(sum(cx) / 2 / w, 4), round(sum(cy) / 2 / h, 4), round(iod, 4)]
print(json.dumps(out))
`

console.log('Detecting eyes across avatars…')
const raw = execFileSync(PYTHON, ['-c', DETECT, AVATAR_DIR], { maxBuffer: 32 * 1024 * 1024 })
const measured = JSON.parse(raw.toString())

const all = fs.readdirSync(AVATAR_DIR).filter(f => f.toLowerCase().endsWith('.png')).sort()
const bySet = {}
for (const f of all) {
  const set = f.split('_')[0]
  bySet[set] ||= { total: 0, hit: 0 }
  bySet[set].total++
  if (measured[f]) bySet[set].hit++
}
for (const [set, s] of Object.entries(bySet)) {
  console.log(`  ${set.padEnd(8)} ${s.hit}/${s.total} detected`)
}

const entries = Object.entries(measured)
  .map(([name, v]) => `  '${name}': [${v.join(', ')}],`)
  .join('\n')

fs.writeFileSync(OUT, `/**
 * GENERATED by scripts/calibrate-avatar-rigs.mjs — do not edit by hand.
 *
 * Per-avatar face anchors: [eyeX, eyeY, interOcularDistance], all normalised to
 * image dimensions. Everything else the renderer needs is derived from these in
 * lib/avatar-motion.ts, so the anthropometric ratios stay in code where they
 * can be read and the measurements stay in data where they can be regenerated.
 *
 * Avatars absent from this table were not detected (the robot set, and a
 * handful of human portraits) and fall back to their set default.
 */
export const AVATAR_ANCHORS: Record<string, [number, number, number]> = {
${entries}
}
`)

// Served copy. The mobile app resolves every asset relative to the host URL, so
// fetching anchors from the host keeps it in sync as avatars are added — a
// bundled copy goes stale the first time someone adds one.
const total = all.length
const JSON_OUT = path.join(AVATAR_DIR, 'face-anchors.json')
fs.writeFileSync(JSON_OUT, JSON.stringify({
  version: 1,
  note: 'Per-avatar face anchors for animated call avatars. Normalised 0..1 to image dimensions. Avatars ABSENT from this table are expected, not errors — use the setDefaults fallback.',
  derivation: {
    comment: 'Everything else is derived from inter-ocular distance (IOD), which is invariant to how tightly the portrait is cropped.',
    mouthY: 'eyeY + 1.04 * iod',
    jawTop: 'eyeY + 0.72 * iod',
    mouthWidth: '0.62 * iod',
    eyeWidth: '0.56 * iod',
    mouthX: 'eyeX',
  },
  setDefaults: {
    men: { eyeX: 0.5, eyeY: 0.38, iod: 0.16, jawScale: 1 },
    women: { eyeX: 0.5, eyeY: 0.41, iod: 0.155, jawScale: 1 },
    robots: { eyeX: 0.5, eyeY: 0.365, iod: 0.29, jawScale: 0.55 },
  },
  coverage: {
    total,
    measured: Object.keys(measured).length,
    fallback: total - Object.keys(measured).length,
    bySet: Object.fromEntries(Object.entries(bySet).map(([k, v]) => [k, { total: v.total, measured: v.hit }])),
  },
  anchors: Object.fromEntries(Object.entries(measured).map(([k, v]) => [k, { eyeX: v[0], eyeY: v[1], iod: v[2] }])),
}, null, 2))

console.log(`\nWrote ${Object.keys(measured).length} anchors to:`)
console.log(`  ${path.relative(ROOT, OUT)}`)
console.log(`  ${path.relative(ROOT, JSON_OUT)}`)
console.log(`  ${total - Object.keys(measured).length} avatars fall back to set defaults (expected, not errors)`)
